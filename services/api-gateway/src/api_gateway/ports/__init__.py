"""Ports the gateway depends on. Adapters: HTTP (identity-service), Redis (rate limiting)."""

from __future__ import annotations

from typing import Any, Protocol

from opspilot_common.resilience import BreakerSnapshot

Json = dict[str, Any]


class DownstreamError(Exception):
    """A service answered with a client error; pass status and body through unchanged."""

    def __init__(self, status_code: int, body: Json) -> None:
        super().__init__(f"downstream {status_code}")
        self.status_code, self.body = status_code, body


class IdentityPort(Protocol):
    async def sign_in(self, email: str, password: str) -> Json: ...
    async def sign_in_mfa(self, challenge_token: str, code: str, new_password: str | None) -> Json: ...
    async def renew(self, token: str) -> Json: ...
    async def sign_out(self, token: str, reason: str) -> None: ...
    async def me(self, token: str) -> Json: ...
    async def roles(self, token: str) -> list[Json]: ...
    async def list_users(self, token: str) -> list[Json]: ...
    async def create_user(self, token: str, body: Json) -> Json: ...
    async def update_user(self, token: str, user_id: str, body: Json) -> Json: ...
    async def reset_mfa(self, token: str, user_id: str) -> Json: ...
    async def reset_password(self, token: str, user_id: str, body: Json) -> Json: ...


class RateLimiter(Protocol):
    async def allow(self, key: str, limit: int, window_seconds: int) -> bool: ...


class SettingsPort(Protocol):
    async def list_sections(self, token: str) -> list[Json]: ...
    async def get_section(self, token: str, section: str) -> Json: ...
    async def save_section(self, token: str, section: str, body: Json) -> Json: ...
    async def test_section(self, token: str, section: str, body: Json) -> Json: ...


class MailPort(Protocol):
    async def status(self, token: str) -> Json: ...
    async def poll(self, token: str) -> Json: ...


class AuditPort(Protocol):
    async def entries(self, token: str, params: dict[str, str]) -> Json: ...


class PrivacyPort(Protocol):
    async def reveal(self, token: str, body: Json) -> Json: ...


class ApprovalPort(Protocol):
    async def queue(self, token: str, params: dict[str, str]) -> Json: ...
    async def get(self, token: str, approval_id: str) -> Json: ...
    async def decide(self, token: str, approval_id: str, body: Json) -> Json: ...


class RunsPort(Protocol):
    async def summary(self, token: str) -> Json: ...


class OpsPort(Protocol):
    async def evidence(self, token: str, approval_id: str) -> Json: ...


class ReportingPort(Protocol):
    async def dashboard(self, token: str) -> Json: ...
    async def timeline(self, token: str, key: str) -> Json: ...


class BreakerStateReader(Protocol):
    async def snapshots(self) -> dict[str, BreakerSnapshot]: ...
